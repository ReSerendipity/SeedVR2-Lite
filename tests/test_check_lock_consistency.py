"""`scripts/check_lock_consistency.py` 的行为测试（CPU-only，不联网、不读真实锁文件）。

重点锁五件事，因为它们各对应一次真实踩过的坑（见被测脚本模块 docstring）：
1. **PEP 503 名等价**：`-`/`_`/`.` 与大小写在分发包名里全部等价，不做归一化就会把
   `pydantic_core` 与 `pydantic-core` 当成两个包，凭空报「仅一侧存在」。
2. **CRLF/LF 归一化**：uv 在不同 runner 上可能写出不同行尾；行尾差异不是锁漂移，
   且归一化必须发生在 header 匹配**之前**（CRLF 的 header 行同样要被跳过）。
3. **uv header 两行跳过 + hash 续行归属**：autogenerated 头两行不能被当成包；多行
   `--hash=` 续行必须计入紧前的包名行，孤立 hash 行（包名行之前）不得计数。
4. **差异四分类不互窜**：版本漂移 / 仅 committed / 仅 export 各自进各自的 FAIL 段落；
   hash 覆盖差异只允许 INFO——它绝不判失败（pip --require-hashes 在构建时兜底）。
5. **退出码契约**：一致 0 / 漂移 1，且 FAIL 输出必须点名漂移包（否则 CI 日志不可定位）。
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
SCRIPT = REPO / "scripts" / "check_lock_consistency.py"

HEADER = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    uv export --format requirements-txt --no-dev --no-emit-project "
    "--emit-index-url -o requirements-container-lock.txt\n"
)
H_A = "a" * 64
H_B = "b" * 64
H_C = "c" * 64
H_D = "d" * 64
H_ORPHAN = "0" * 64


def _load_gate():
    """按文件路径加载门禁脚本（scripts/ 不在包内，沿用仓内 importlib 装载惯例）。"""
    spec = importlib.util.spec_from_file_location("check_lock_consistency", SCRIPT)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


gate = _load_gate()


def _write_req(path: Path, text_lf: str, newline: str = "\n") -> Path:
    """用指定行尾现造 requirements 文本（不读任何真实文件、不联网）。"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text_lf.replace("\n", newline).encode("utf-8"))
    return path


def _run_main(monkeypatch, tmp_path, committed: str, exported: str, list_info: bool = False):
    com = _write_req(tmp_path / "committed.txt", committed)
    exp = _write_req(tmp_path / "export.txt", exported)
    argv = [
        "check_lock_consistency.py",
        "--committed",
        str(com),
        "--export",
        str(exp),
    ]
    if list_info:
        argv.append("--list-info")
    monkeypatch.setattr(sys, "argv", argv)
    return gate.main()


# --------------------------------------------------------------------------
# 1. PEP 503 名归一化：连字符 / 下划线 / 点 / 大小写 / 连续分隔符
# --------------------------------------------------------------------------


@pytest.mark.parametrize(
    "raw, expected",
    [
        ("requests", "requests"),
        ("Typing_Extensions", "typing-extensions"),
        ("zope.interface", "zope-interface"),
        ("Foo-Bar.BAZ", "foo-bar-baz"),
        ("a..b__c--d", "a-b-c-d"),  # 连续分隔符必须塌成一个
        ("_.foo._", "-foo-"),  # 首尾分隔符同样归一
    ],
)
def test_normalize_name_follows_pep503(raw, expected):
    assert gate.normalize_name(raw) == expected


def test_pep503_spellings_collapse_to_same_key():
    spellings = ["pydantic_core", "Pydantic-Core", "pydantic.core", "PYDANTIC__CORE"]
    assert {gate.normalize_name(s) for s in spellings} == {"pydantic-core"}


# --------------------------------------------------------------------------
# 2. CRLF / CR / LF 行尾归一化（且 header 匹配在归一化之后）
# --------------------------------------------------------------------------


@pytest.mark.parametrize("newline", ["\n", "\r\n", "\r"])
def test_lf_crlf_cr_parse_identically(tmp_path, newline):
    text = (
        HEADER + "alpha==1.0.0 \\\n"
        f"    --hash=sha256:{H_A} \\\n"
        f"    --hash=sha256:{H_B}\n"
        "beta==2.0.0\n"
        f"    --hash=sha256:{H_C}\n"
    )
    lf = _write_req(tmp_path / "lf.txt", text, "\n")
    other = _write_req(tmp_path / "other.txt", text, newline)

    pins_lf, counts_lf, hashes_lf = gate.load(str(lf))
    pins, counts, hashes = gate.load(str(other))
    assert pins == pins_lf == {"alpha": "1.0.0", "beta": "2.0.0"}
    assert counts == counts_lf == {"alpha": 2, "beta": 1}
    assert hashes == hashes_lf == {"alpha": {H_A, H_B}, "beta": {H_C}}


# --------------------------------------------------------------------------
# 3. uv 导出 header 两行跳过 + 多行 --hash 续行归属
# --------------------------------------------------------------------------


def test_uv_export_header_lines_are_skipped(tmp_path):
    text = HEADER + "alpha==1.0.0\n"
    pins, _counts, _hashes = gate.load(str(_write_req(tmp_path / "r.txt", text)))
    assert set(pins) == {"alpha"}
    # header 文本都不是合法包名，一旦没被跳过就会多出形如 "this-file-was-..." 的键
    assert all(not k.startswith(("this", "uv-export")) for k in pins)


def test_hash_continuation_lines_belong_to_current_pin(tmp_path):
    # 开头先放一个孤立 hash 行：此时还没有任何包名行，必须被丢弃而非记到别人头上。
    text = (
        HEADER + f"    --hash=sha256:{H_ORPHAN}\n"
        "alpha==1.0.0 \\\n"
        f"    --hash=sha256:{H_A} \\\n"
        f"    --hash=sha256:{H_B}\n"
        "\n"
        "beta==2.0.0\n"
        f"    --hash=sha256:{H_C}\n"
        f"    --hash=sha256:{H_C}\n"  # 重复 hash：计数 2，但集合去重为 1（分类比集合）
    )
    pins, counts, hashes = gate.load(str(_write_req(tmp_path / "r.txt", text)))
    assert pins == {"alpha": "1.0.0", "beta": "2.0.0"}
    assert counts == {"alpha": 2, "beta": 2}
    assert hashes == {"alpha": {H_A, H_B}, "beta": {H_C}}
    assert H_ORPHAN not in (hashes["alpha"] | hashes["beta"])


def test_pep503_spellings_across_files_are_not_drift(tmp_path, monkeypatch, capsys):
    """committed 用 Pydantic_Core、export 用 pydantic.core：同包同名，必须判一致。"""
    committed = HEADER + "Pydantic_Core==2.9.0\n"
    exported = HEADER + "pydantic.core==2.9.0\n"
    rc = _run_main(monkeypatch, tmp_path, committed, exported)
    assert rc == 0
    out = capsys.readouterr().out
    assert "PASS" in out and "FAIL" not in out


# --------------------------------------------------------------------------
# 4. 差异四分类：版本漂移 / 仅 committed / 仅 export / hash 覆盖差异（仅 INFO）
# --------------------------------------------------------------------------


def test_hash_coverage_only_difference_is_info_never_failure(tmp_path, monkeypatch, capsys):
    committed = HEADER + f"fonttools==4.53.0\n    --hash=sha256:{H_A}\n    --hash=sha256:{H_B}\n"
    exported = HEADER + f"fonttools==4.53.0\n    --hash=sha256:{H_A}\n"

    # 默认不打印 INFO，但退出码必须是 0
    rc = _run_main(monkeypatch, tmp_path, committed, exported)
    out = capsys.readouterr().out
    assert rc == 0
    assert "PASS" in out and "INFO" not in out

    # --list-info 下只多出 INFO 行，退出码依旧是 0（不得判失败）
    rc = _run_main(monkeypatch, tmp_path, committed, exported, list_info=True)
    out = capsys.readouterr().out
    assert rc == 0
    assert "INFO hash coverage differs for fonttools==4.53.0" in out
    assert "committed 2 hashes, export 1" in out
    assert "not a gate failure" in out
    assert "FAIL" not in out


def test_four_way_classification(tmp_path, monkeypatch, capsys):
    committed = (
        HEADER + "requests==2.31.0\n"
        f"    --hash=sha256:{H_A}\n"
        "onlycom==1.0.0\n"
        f"    --hash=sha256:{H_B}\n"
        "hashpkg==9.9.9\n"
        f"    --hash=sha256:{H_C}\n"
        f"    --hash=sha256:{H_D}\n"
    )
    exported = (
        HEADER + "requests==2.32.3\n"
        f"    --hash=sha256:{H_A}\n"
        "onlyexp==3.1.4\n"
        f"    --hash=sha256:{H_B}\n"
        "hashpkg==9.9.9\n"
        f"    --hash=sha256:{H_C}\n"
    )
    rc = _run_main(monkeypatch, tmp_path, committed, exported, list_info=True)
    out = capsys.readouterr().out
    assert rc == 1
    assert "FAIL" in out
    # 版本漂移：旧 -> 新 点名到行
    assert "requests: 2.31.0 -> 2.32.3" in out
    # 单侧存在：各进各的段落
    assert "onlycom==1.0.0" in out
    assert "onlyexp==3.1.4" in out
    # hash 覆盖差异只允许出现在 INFO 行，不得进任何 FAIL 段落
    assert out.count("hashpkg") == 1
    assert "INFO hash coverage differs for hashpkg==9.9.9" in out


# --------------------------------------------------------------------------
# 5. main 退出码契约 + FAIL 输出含漂移包名
# --------------------------------------------------------------------------


def test_main_exit_codes_and_fail_names_drifted_package(tmp_path, monkeypatch, capsys):
    identical = HEADER + "click==8.1.7\n"
    rc = _run_main(monkeypatch, tmp_path, identical, identical)
    out = capsys.readouterr().out
    assert rc == 0
    assert "PASS" in out and "FAIL" not in out

    drifted = HEADER + "click==8.1.8\n"
    rc = _run_main(monkeypatch, tmp_path, identical, drifted)
    out = capsys.readouterr().out
    assert rc == 1
    assert "FAIL" in out
    assert "click" in out and "8.1.7 -> 8.1.8" in out
    assert "PASS" not in out
