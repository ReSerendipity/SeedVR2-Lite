"""Gate: requirements-container-lock.txt must agree with uv.lock's pinned versions.

Why this exists: Dependabot edits the *exported* requirements files in place and never
re-runs `uv lock`, so uv.lock keeps the older version while the file the Docker image
installs from already moved. `64ee025` (#160) and `943c2fe` (#155) each did that, and
`603f279` had to roll the container lock back to a pre-bump blob to make docker-publish
green again. Comparing the committed export against a fresh `uv export --frozen` catches
the divergence in the PR that introduces it, instead of ~35 minutes later as a red
docker build.

Scope is deliberately the *name==version pin set*, not raw bytes, because a byte
comparison can never be satisfiable here:
  - `torch==2.13.0+cu132` carries a hand-added manylinux wheel hash (26f6a7f). uv.lock
    records no hash for that local version, so `uv export` cannot reproduce the line,
    and the Dockerfile install relies on it being there.
  - fonttools/numpy in the committed file list more wheel hashes than uv.lock records.
  - the committed file's header line embeds the `-o` path of whoever ran the export.
Those are hash-coverage differences, and pip's own `--require-hashes` mode enforces them
at docker build time; they are reported here as INFO, not as failure.
"""

from __future__ import annotations

import argparse
import re
import sys

HEADER_PATTERNS = (
    re.compile(r"^# This file was autogenerated by uv via the following command:$"),
    re.compile(r"^#\s+uv export\b"),
)
PIN = re.compile(r"^([A-Za-z0-9._\-]+)==([^\s;\\]+)")
HASH = re.compile(r"^\s+--hash=sha256:([0-9a-f]{64})")


def normalize_name(raw: str) -> str:
    # PEP 503: `-`, `_`, `.` and case are all interchangeable in a distribution name.
    # Without this, `pydantic_core` and `pydantic-core` read as two different packages.
    return re.sub(r"[-_.]+", "-", raw).lower()


def load(path: str) -> tuple[dict[str, str], dict[str, int], dict[str, set[str]]]:
    with open(path, "rb") as handle:
        raw = handle.read()
    # Newline normalisation is mandatory, not cosmetic: .gitattributes forces eol=lf in
    # the repo, but uv writes whatever the runner's checkout handed it, so the same
    # content can arrive as LF or CRLF. A line-ending difference is not lock drift and
    # must never be able to redden the gate.
    text = raw.decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")

    lines = text.split("\n")
    start = 0
    while start < len(lines) and any(p.match(lines[start]) for p in HEADER_PATTERNS):
        start += 1

    pins: dict[str, str] = {}
    counts: dict[str, int] = {}
    hashes: dict[str, set[str]] = {}
    current = None
    for line in lines[start:]:
        m = PIN.match(line)
        if m:
            current = normalize_name(m.group(1))
            pins[current] = m.group(2)
            counts[current] = 0
            hashes[current] = set()
            continue
        h = HASH.match(line)
        if h and current is not None:
            counts[current] += 1
            hashes[current].add(h.group(1))
    return pins, counts, hashes


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--export", required=True, help="freshly exported requirements file")
    ap.add_argument("--committed", required=True, help="requirements file in the repo")
    ap.add_argument(
        "--list-info", action="store_true", help="also print hash-coverage differences (informational only)"
    )
    a = ap.parse_args()

    exp_pins, exp_counts, exp_hashes = load(a.export)
    com_pins, com_counts, com_hashes = load(a.committed)

    only_committed = sorted(k for k in com_pins if k not in exp_pins)
    only_export = sorted(k for k in exp_pins if k not in com_pins)
    mismatched = sorted((k, com_pins[k], exp_pins[k]) for k in com_pins if k in exp_pins and com_pins[k] != exp_pins[k])
    hash_only = sorted(k for k in com_pins if k in exp_pins and com_hashes[k] != exp_hashes[k])

    print(f"committed : {a.committed}  ({len(com_pins)} pinned distributions)")
    print(f"export    : {a.export}  ({len(exp_pins)} pinned distributions)")
    if a.list_info and hash_only:
        for k in hash_only:
            print(
                f"  INFO hash coverage differs for {k}=="
                f"{com_pins[k]}: committed {com_counts[k]} hashes, "
                f"export {exp_counts[k]} (not a gate failure, see module docstring)"
            )

    if not (only_committed or only_export or mismatched):
        print(f"PASS: {a.committed} matches uv.lock on all {len(exp_pins)} pinned versions")
        return 0

    print("\nFAIL: requirements-container-lock.txt is out of sync with uv.lock")
    print("  - drifted versions (committed -> what uv.lock exports):")
    for name, c, e in mismatched:
        print(f"      {name}: {c} -> {e}")
    print("  - present only in the committed export (uv.lock does not have it):")
    for name in only_committed:
        print(f"      {name}=={com_pins[name]}")
    print("  - present only in uv.lock's export (missing from the committed file):")
    for name in only_export:
        print(f"      {name}=={exp_pins[name]}")
    print(
        "\nRe-sync with the uv version this gate pins (see .github/workflows/" "lock-consistency.yml), then re-export:"
    )
    print("  uv lock --upgrade-package <name>==<version>   # per drifted package")
    print(
        "  uv export --format requirements-txt --no-dev --no-emit-project "
        "--emit-index-url -o requirements-container-lock.txt"
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
